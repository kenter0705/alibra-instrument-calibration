export function getDailyQualityQuote(date = new Date()) {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul", year: "numeric", month: "2-digit", day: "2-digit",
  }).formatToParts(date);
  const values = Object.fromEntries(parts.map(({ type, value }) => [type, value]));
  const today = Date.UTC(Number(values.year), Number(values.month) - 1, Number(values.day));
  const start = Date.UTC(2026, 0, 1);
  const dayNumber = Math.floor((today - start) / 86_400_000);
  const index = ((dayNumber % qualityQuotes.length) + qualityQuotes.length) % qualityQuotes.length;
  return { text: qualityQuotes[index], number: index + 1, total: qualityQuotes.length };
}
